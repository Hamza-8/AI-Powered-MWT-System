"""Write exact construction-time layer/parameter evidence; no trained weights implied."""
from __future__ import annotations
import inspect
import json
from pathlib import Path
import torch
from torch import nn
from microscan.models import MSRNN, SegmentationUNet
from microscan.gan import CycleGAN3D
from microscan.physics import HeadsetForwardOperator


def describe(name, model):
    layers=[]
    for path,module in model.named_modules():
        own=list(module.parameters(recurse=False))
        if not list(module.children()) or own:
            fields={}
            for key in ('in_channels','out_channels','kernel_size','stride','padding','dilation','output_padding','num_groups','num_channels','in_features','out_features'):
                if hasattr(module,key):fields[key]=getattr(module,key)
            if hasattr(module,'bias'): fields['bias']=getattr(module,'bias') is not None
            try: source_line=inspect.getsourcelines(type(module))[1]
            except (OSError,TypeError): source_line=None
            layers.append({'path':path,'type':type(module).__name__,'specification':fields,'own_parameters':sum(p.numel() for p in own),'trainable_parameters':sum(p.numel() for p in own if p.requires_grad),'class_source':inspect.getsourcefile(type(module)),'class_line':source_line})
    return {'model':name,'parameters':sum(p.numel() for p in model.parameters()),'trainable_parameters':sum(p.numel() for p in model.parameters() if p.requires_grad),'layers':layers}


def main():
    torch.manual_seed(17)
    models={'MSRNN_A_B':MSRNN(),'SegmentationUNet_multiclass':SegmentationUNet(),'CycleGAN3D_G_F_Dx_Dy':CycleGAN3D(),'HeadsetForwardOperator':HeadsetForwardOperator()}
    results=[describe(name,m) for name,m in models.items()]
    root=Path('docs'); root.mkdir(exist_ok=True)
    (root/'architecture_layers.json').write_text(json.dumps({'schema_version':1,'evidence':'untrained construction introspection; no performance claim','torch_version':torch.__version__,'models':results},indent=2)+'\n')
    table=['# Exact constructed layers','', 'Generated by `python scripts/describe_architecture.py`. Counts include all model parameters; the Phi count is independent of A/B deployment. No training or inference accuracy is implied.','']
    for result in results:
        table += ['## '+result['model'],'',f"Total parameters: {result['parameters']:,}.",'','| Path | Layer | Specification | Own parameters |','|---|---|---|---|']
        for l in result['layers']:
            spec=', '.join(f'{k}={v}' for k,v in l['specification'].items())
            table.append(f"| `{l['path']}` | {l['type']} | {spec} | {l['own_parameters']:,} |")
        table.append('')
    (root/'ARCHITECTURE_LAYERS.md').write_text('\n'.join(table)+'\n')
    for r in results:print(r['model'],r['parameters'])

if __name__=='__main__':main()
